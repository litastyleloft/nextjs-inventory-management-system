// Generates app/gildedglow.css from the design sources, the same way
// design/build.py assembles the <style> block of every page in design/html:
//   1. tokens.json  -> :root custom properties (light values)
//   2. components/bundle.css (font @import removed; fonts load via next/font)
//   3. the shared "Page composition" rules from src/partials/shell_top.html
//
// Run after changing anything in design/src:  node scripts/build-gildedglow.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const ds = join(root, "design", "src", "design-system");
const read = (p) => readFileSync(p, "utf8");

const tok = JSON.parse(read(join(ds, "tokens.json")));
const lines = [":root {"];
for (const t of tok.color.tokens) lines.push(`  --${t.name}: ${t.value.light};`);
// Shadow tokens are {light: "..."} objects. design/build.py prints them as a
// Python dict (invalid CSS, so the design/html pages render with no shadows);
// here we take the light value the tokens intend.
const val = (v) => (v && typeof v === "object" ? v.light : v);
for (const f of ["shadow", "spacing", "radius", "layout", "zIndex"])
  for (const t of tok[f].tokens) lines.push(`  --${t.name}: ${val(t.value)};`);
for (const [k, v] of Object.entries(tok.type.families)) lines.push(`  --font-${k}: ${v};`);
lines.push("}");

const bundle = read(join(ds, "components", "bundle.css")).replace(/@import url\([^)]*\);\n*/g, "");

const shellTop = read(join(root, "design", "src", "partials", "shell_top.html"));
const composition = shellTop
  .split("/* ===== Page composition ===== */")[1]
  .split("{{PAGE_CSS}}")[0]
  .trim();

const out = [
  "/* GENERATED by scripts/build-gildedglow.mjs from design/src. Do not edit by hand. */",
  "",
  "/* ===== LTS Solution design tokens (design/src/design-system/tokens.json) ===== */",
  lines.join("\n"),
  "",
  "/* ===== LTS Solution component styles (design/src/design-system/components/bundle.css) ===== */",
  bundle.trim(),
  "",
  "/* ===== Page composition (design/src/partials/shell_top.html) ===== */",
  composition,
  "",
].join("\n");

writeFileSync(join(root, "app", "gildedglow.css"), out, "utf8");
console.log("wrote app/gildedglow.css");
