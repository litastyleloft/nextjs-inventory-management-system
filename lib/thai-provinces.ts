/** The region for a province (or a free-text city), "ต่างประเทศ" for other countries, or "". */
export function regionOf(city?: string, country?: string): string {
  if (city === ABROAD) return ABROAD;
  if (country && country !== "ไทย" && country !== "ประเทศไทย") return ABROAD;
  const c = String(city || "").replace(/^(จังหวัด|จ\.|อำเภอ|อ\.|เขต)\s*/, "").replace(/\s+/g, "");
  if (!c) return "";
  for (const r in REGIONS) {
    for (const n of REGIONS[r].split(" ")) {
      if (c === n || c.indexOf(n) >= 0 || (c.length >= 3 && n.indexOf(c) === 0)) return r;
    }
  }
  return "";
}
